/**
 * Best-effort localStorage access for optional caches and preferences only.
 * The getter itself can throw in embedded/restricted contexts. No fallback
 * stores identity, and a storage result must never decide authentication.
 */
export function getOptionalStorageItem(key: string): string | null {
  try {
    if (typeof window === "undefined") return null;
    return window.localStorage.getItem(key);
  } catch {
    return null;
  }
}

export function setOptionalStorageItem(key: string, value: string): boolean {
  try {
    if (typeof window === "undefined") return false;
    window.localStorage.setItem(key, value);
    return true;
  } catch {
    return false;
  }
}

export function removeOptionalStorageItem(key: string): boolean {
  try {
    if (typeof window === "undefined") return false;
    window.localStorage.removeItem(key);
    return true;
  } catch {
    return false;
  }
}
